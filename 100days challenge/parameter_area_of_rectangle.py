# Prompt the user for the width and length of the rectangle
width=float(input("Enter the width of the rectagle :"))
length=float(input("Enter the height of the rectagle :"))


# Calculate the perimeter
perimeter =2*(width+length)

# Calculate the area
area=width*length

# Display the results
print("Perimeter of the rectagle:",perimeter)
print("Area of the rectagle:",area)







